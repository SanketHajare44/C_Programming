// Accept one number from user and print that number of * on screen.

/////////////////////////////////////////////////////////////////
//
//  Required header files
//
/////////////////////////////////////////////////////////////////

#include<stdio.h>

/////////////////////////////////////////////////////////////////
//
//  Function name : Accept
//  Description :   It is used Display * on screen 
//  Input :         
//  Output :        void
//  Author :        Sanket Sadashiv Hajare
//  Date :          16/10/2025
//
/////////////////////////////////////////////////////////////////

void Accept(int iNo)
{
    int iCnt = 0;

    for(iCnt=1; iCnt<=iNo; iCnt++)  // Business logic
    {
        printf("*");
    }
    printf("\n");
    
}// End Accept Function

/////////////////////////////////////////////////////////////////
//
//  Time Complexity : O(N)
//
/////////////////////////////////////////////////////////////////

/////////////////////////////////////////////////////////////////
//
//  Entry point function for the application
//
/////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    iValue = 5;

    Accept(iValue);                 // Function call

    return 0;

}// End main function

