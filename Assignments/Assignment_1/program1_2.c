void Display()
{
    int i = 0;                      // Loop counter
    for(i=1; i<=5; i++)
    {
        printf("Marvellous\n");     // Business logic
    }
}// End Divide Function

/////////////////////////////////////////////////////////////////
//
//  Time Complexity : O(1)
//
/////////////////////////////////////////////////////////////////

/////////////////////////////////////////////////////////////////
//
//  Entry point function for the application
//
/////////////////////////////////////////////////////////////////

int main()
{
    Display();                      // Function call
    return 0;
}// End main function

