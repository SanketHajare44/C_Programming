// Accept amount in US dollar and returns its corresponding value in indian currency consider 1$ as 70 rupees.

///////////////////////////////////////////////////////////////////////////////
//
//  Requied header files
//
///////////////////////////////////////////////////////////////////////////////

#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////
//
//  Function name : DollarToINR
//  Description :   It is perform conversion of INR to Dollar
//  Input :         Integer
//  Output :        Integer
//  Author :        Sanket Sadashiv Hajare
//  Date :          23/10/2025
//
///////////////////////////////////////////////////////////////////////////////

int DollarToINR(int iNo)
{   
    int INR = 0;
    INR = iNo*70;                               // Business logic

    return INR;

}// End of DollarToINR function

///////////////////////////////////////////////////////////////////////////////
//
//  Time Complexity : O(1)
//
///////////////////////////////////////////////////////////////////////////////

///////////////////////////////////////////////////////////////////////////////
//
//  Entry point function for the application
//
///////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;                             // To accept user input
    int iRet = 0;                               // To store the result

    printf("Enter nnumber of USD :\n");
    scanf("%d",&iValue);

    iRet = DollarToINR(iValue);                 // Function call

    printf("Value in INR is : %d\n",iRet);

    return 0;
}// End of main

