// Write a program which accept N from user and print all odd numbers up to N

///////////////////////////////////////////////////////////////////////////////
//
//  Requied header files
//
///////////////////////////////////////////////////////////////////////////////

#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////
//
//  Function name : OddDisplay
//  Description :   It is use to print all odd number till that user input number
//  Input :         Integer
//  Output :        Void
//  Author :        Sanket Sadashiv Hajare
//  Date :          21/10/2025
//
///////////////////////////////////////////////////////////////////////////////

void OddDisplay(int iNo)
{
    int iCnt = 0;

    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        if((iCnt % 2) != 0)                 // Business logic
        {
            printf("%d\t",iCnt);
        }
    }
    printf("\n");

}// End of OddDisplay function

///////////////////////////////////////////////////////////////////////////////
//
//  Time Complexity : O(N)
//
///////////////////////////////////////////////////////////////////////////////

///////////////////////////////////////////////////////////////////////////////
//
//  Entry point function for the application
//
///////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;                         // To accep user input

    printf("Enter number :\n");
    scanf("%d",&iValue);

    OddDisplay(iValue);                     // Function call

    return 0;
}// End of main

